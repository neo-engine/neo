    void parseKanaDigraph( const char* p_string, u32& p_start, u16 p_outCodes[ 2 ],
                           u8& p_outCodesLen ) {
        p_outCodesLen = 0;
        // spaces are verbatim
        if( p_string[ p_start ] == ' ' ) {
            p_outCodes[ 0 ] = ' ';
            p_outCodesLen   = 1;
            p_start += 1;
            return;
        }
        if( !p_string[ p_start + 1 ] ) {
            p_outCodes[ 0 ] = 0;
            p_outCodesLen   = 0;
            p_start += 1;
            return;
        }
        p_outCodes[ 0 ]
            = KANA::digraphToGlyphOrderIndex( p_string[ p_start ], p_string[ p_start + 1 ] );
        p_outCodesLen = !!p_outCodes[ 0 ];
        p_start += 2;
        if( !p_outCodesLen ) {
            p_outCodesLen = 0;
            return;
        }

        // check for yoon merge; yoon marker comes first
        if( p_string[ p_start + 3 ] ) {
            u8 c0 = 0, c1 = 0;
            if( KANA::yoonExpand( p_string[ p_start ], p_string[ p_start + 2 ],
                                  p_string[ p_start + 3 ], c0, c1 ) ) {
                p_outCodes[ 0 ] = KANA_START + c0;
                p_outCodes[ 1 ] = KANA_START + c1;
                p_outCodesLen   = 2;
                p_start += 2;
                return;
            }
        }
        const u8* cells = KANA::CELLS[ p_outCodes[ 0 ] ];
        if( cells[ 0 ] == KANA::NONE ) {
            p_outCodesLen = 0;
            return;
        }
        p_outCodes[ 0 ] = KANA_START + cells[ 0 ];
        if( cells[ 1 ] != KANA::NONE ) {
            p_outCodes[ 1 ] = KANA_START + cells[ 1 ];
            p_outCodesLen   = 2;
        } else {
            p_outCodesLen = 1;
        }
    }

    void shiftchar( u16& p_val ) {
        if( isUpper( p_val ) ) {
            p_val = valToUpper( p_val, UPPER_START );
            return;
        }
        if( isLower( p_val ) ) {
            p_val = valToLower( p_val, LOWER_START );
            return;
        }

        if( p_val == '.' ) {
            p_val = 26;
            return;
        }
        if( p_val == ',' ) {
            p_val = 27;
            return;
        }
        if( p_val == ' ' ) {
            p_val = 29;
            return;
        }
        if( isKana( p_val ) ) {
            p_val = valToKana( p_val, KANA_START );
            return;
        }
        return;
    }
